"""Job orchestration: each job runs in a background thread and persists its state as JSON."""
import json
import re
import threading
import time
import traceback
import uuid
from dataclasses import asdict, dataclass, field
from pathlib import Path

from . import ai, editor, graphics, media, music, tts, youtube
from .config import JOBS_DIR, MAX_DESCRIPTION, MAX_HASHTAGS, MAX_TAGS_CHARS, MAX_TITLE

MUSIC_CREDIT = "Music: original background track generated by AutoYT-manager (no third-party samples)."


@dataclass
class Options:
    privacy: str = "private"            # private | unlisted | public
    music_mood: str = "auto"            # auto | calm | upbeat | lofi | epic | none
    replace_audio: bool = False         # drop the clip's own audio (safest against music claims)
    title_card: bool = True
    auto_upload: bool = False
    made_for_kids: bool = False
    synthetic_media: bool = False       # YouTube "altered or synthetic content" disclosure
    target_seconds: int = 60            # prompt mode only
    ai_provider: str = "gemini"         # gemini | claude | openai
    ai_decides: bool = False            # video mode: skip the choosing step and use the AI's top picks


@dataclass
class Job:
    id: str
    mode: str                           # "video" | "prompt"
    created: float
    options: Options
    source: str | None = None           # uploaded file path (video mode)
    prompt: str = ""                    # notes (video mode) or idea (prompt mode)
    # queued | processing | choosing | ready | needs_review | uploading | uploaded | failed
    status: str = "queued"
    step: str = ""
    progress: float = 0.0
    error: str | None = None
    metadata: dict = field(default_factory=dict)
    copyright: dict = field(default_factory=dict)
    files: dict = field(default_factory=dict)
    youtube: dict = field(default_factory=dict)
    suggestions: dict = field(default_factory=dict)   # video mode: AI options to choose from
    choices: dict = field(default_factory=dict)       # video mode: what the creator picked
    log: list = field(default_factory=list)

    @property
    def dir(self) -> Path:
        return JOBS_DIR / self.id

    def save(self) -> None:
        self.dir.mkdir(parents=True, exist_ok=True)
        tmp = self.dir / "job.json.tmp"
        tmp.write_text(json.dumps(asdict(self), indent=2, ensure_ascii=False), encoding="utf-8")
        tmp.replace(self.dir / "job.json")

    def set(self, step: str, progress: float) -> None:
        self.step, self.progress = step, progress
        self.log.append({"t": time.time(), "msg": step})
        self.save()


_jobs: dict[str, Job] = {}
_lock = threading.Lock()


def _load_all() -> None:
    for f in JOBS_DIR.glob("*/job.json"):
        try:
            d = json.loads(f.read_text(encoding="utf-8"))
            d["options"] = Options(**d.get("options", {}))
            job = Job(**d)
            if job.status in ("queued", "processing", "uploading"):  # interrupted by a restart
                job.status, job.error = "failed", "The app was restarted while this job was running. Retry it."
            _jobs[job.id] = job
        except Exception:
            continue


_load_all()


def list_jobs() -> list[Job]:
    return sorted(_jobs.values(), key=lambda j: j.created, reverse=True)


def get_job(job_id: str) -> Job | None:
    return _jobs.get(job_id)


def create_job(mode: str, options: Options, prompt: str = "", source: Path | None = None) -> Job:
    job = Job(id=uuid.uuid4().hex[:12], mode=mode, created=time.time(), options=options,
              prompt=prompt, source=str(source) if source else None)
    with _lock:
        _jobs[job.id] = job
    job.save()
    start(job)
    return job


def start(job: Job) -> None:
    job.status, job.error, job.progress = "queued", None, 0.0
    job.save()
    threading.Thread(target=_run, args=(job,), daemon=True, name=f"job-{job.id}").start()


def _run(job: Job) -> None:
    try:
        job.status = "processing"
        if job.mode == "video":
            if not job.suggestions:
                _suggest_video(job)
            if not job.choices:
                if not job.options.ai_decides:
                    job.status = "choosing"
                    job.set("Suggestions ready: pick your title, thumbnail, music and more", 1.0)
                    return
                _apply_choices(job, default_choices(job))
            _build_video(job)
        else:
            _process_prompt(job)
        _apply_copyright_policy(job)
        job.set("Ready for review" if job.status == "needs_review" else "Ready to upload", 1.0)
        confirmed = job.choices.get("confirm_rights", False)
        if job.options.auto_upload and (job.status == "ready" or (job.status == "needs_review" and confirmed)):
            upload(job, override_review=confirmed)
    except Exception as e:  # surface every failure in the UI instead of killing the thread silently
        job.status, job.error = "failed", str(e) or e.__class__.__name__
        job.log.append({"t": time.time(), "msg": traceback.format_exc(limit=3)})
        job.save()


# ---------------------------------------------------------------- video mode

PREVIEW_MOODS = ["calm", "upbeat", "lofi", "epic"]
PREVIEW_SECONDS = 20


def _suggest_video(job: Job) -> None:
    """Stage 1: analyse the clip and prepare options (titles, descriptions, hashtags, thumbnails, music)."""
    src = Path(job.source)
    job.set("Reading video", 0.03)
    info = media.probe(src)
    if info.width == 0:
        raise RuntimeError("That file has no video stream.")

    job.set("Sampling frames", 0.08)
    frames = media.extract_frames(src, 8, job.dir / "frames", info.duration)
    if not frames:
        raise RuntimeError("Could not extract frames from the video.")

    job.set(f"Writing suggestions with {_ai_label(job)}", 0.15)
    meta = ai.analyze_video(frames, info.duration, job.prompt, info.has_audio, not job.options.replace_audio,
                            provider=job.options.ai_provider)

    job.set("Designing thumbnail options", 0.6)
    thumbs = []
    for i, opt in enumerate(meta["thumbnail_options"][:3]):
        frame = frames[min(opt["frame"], len(frames) - 1)]
        text = _clean(opt.get("text", "")) or "Watch this"
        color = "#%02X%02X%02X" % graphics.hex_color(opt.get("accent_color", ""))
        img = graphics.make_thumbnail(job.dir / "options" / f"thumbnail_{i}.jpg", text, color, frame=frame)
        thumbs.append({"frame": frame.relative_to(job.dir).as_posix(), "text": text, "accent_color": color,
                       "image": img.relative_to(job.dir).as_posix()})

    job.set("Composing music previews", 0.75)
    previews = {}
    for mood in PREVIEW_MOODS:
        wav = music.generate(mood, min(PREVIEW_SECONDS, info.duration + 1), job.dir / "options" / f"music_{mood}.wav",
                             seed=int(job.created))
        previews[mood] = wav.relative_to(job.dir).as_posix()

    hashtags = _clean_hashtags(meta.get("hashtags", []))
    job.suggestions = {
        "titles": [t for t in (_clean(t)[:MAX_TITLE] for t in meta.get("titles", [])) if t] or ["Untitled video"],
        "descriptions": [d for d in (_clean(d) for d in meta.get("descriptions", [])) if d] or [""],
        "hashtags": hashtags,
        "recommended_hashtags": hashtags[:8],
        "tags": _fit_tags([_clean(t).replace(",", " ") for t in meta.get("tags", [])]),
        "category_id": meta.get("category_id") if meta.get("category_id") in ai.CATEGORIES else "22",
        "categories": ai.CATEGORIES,
        "thumbnails": thumbs,
        "music_mood": meta.get("music_mood") if meta.get("music_mood") in ai.MOODS else "calm",
        "music_reason": meta.get("music_reason", ""),
        "music_previews": previews,
        "replace_audio": bool(meta.get("suggest_replace_audio")),
        "title_card": bool(meta.get("suggest_title_card", True)),
        "made_for_kids": bool(meta.get("suggest_made_for_kids")),
        "tips": [t for t in meta.get("tips", []) if t][:4],
        "copyright_review": meta.get("copyright_review", {"risk": "medium", "issues": []}),
        "video": {"duration": info.duration, "has_audio": info.has_audio, "vertical": info.vertical},
    }
    # Show the AI's top picks until the creator chooses.
    _store_metadata(job, {
        "title": job.suggestions["titles"][0], "description": job.suggestions["descriptions"][0],
        "hashtags": job.suggestions["recommended_hashtags"], "tags": job.suggestions["tags"],
        "category_id": job.suggestions["category_id"], "thumbnail_text": thumbs[0]["text"],
        "accent_color": thumbs[0]["accent_color"],
    })
    job.files["thumbnail_preview"] = thumbs[0]["image"]
    job.save()


def default_choices(job: Job) -> dict:
    """The AI's top pick for every option (used for 'Let AI choose everything' and as UI defaults)."""
    s, o = job.suggestions, job.options
    mood = o.music_mood if o.music_mood != "auto" else s["music_mood"]
    return {
        "title": s["titles"][0], "description": s["descriptions"][0],
        "hashtags": s["recommended_hashtags"], "tags": s["tags"], "category_id": s["category_id"],
        "thumbnail_index": 0, "thumbnail_text": s["thumbnails"][0]["text"],
        "music_mood": mood, "replace_audio": o.replace_audio or s["replace_audio"],
        "title_card": s["title_card"] if o.ai_decides else o.title_card,
        "privacy": o.privacy, "made_for_kids": o.made_for_kids, "synthetic_media": o.synthetic_media,
        "auto_upload": o.auto_upload, "confirm_rights": False,
    }


def finalize(job: Job, choices: dict) -> None:
    """Store the creator's picks and start stage 2 (edit + optional upload)."""
    if job.status not in ("choosing", "ready", "needs_review", "failed") or not job.suggestions:
        raise RuntimeError("This video is not waiting for choices.")
    c = {**default_choices(job), **{k: v for k, v in choices.items() if v is not None}}
    s = job.suggestions
    c["thumbnail_index"] = max(0, min(int(c["thumbnail_index"]), len(s["thumbnails"]) - 1))
    if c["music_mood"] not in ai.MOODS:
        c["music_mood"] = s["music_mood"]
    if c["privacy"] not in ("private", "unlisted", "public"):
        c["privacy"] = "private"
    c["category_id"] = c["category_id"] if c["category_id"] in ai.CATEGORIES else s["category_id"]
    _apply_choices(job, c)
    start(job)


def _apply_choices(job: Job, c: dict) -> None:
    """Choices win over the upload-form options (the copyright check and upload read job.options)."""
    job.choices = c
    o = job.options
    o.privacy, o.made_for_kids, o.synthetic_media = c["privacy"], bool(c["made_for_kids"]), bool(c["synthetic_media"])
    o.replace_audio, o.title_card, o.auto_upload = bool(c["replace_audio"]), bool(c["title_card"]), bool(c["auto_upload"])
    o.music_mood = c["music_mood"]
    job.save()


def _build_video(job: Job) -> None:
    """Stage 2: render the final video and thumbnail from the creator's choices."""
    c, s = job.choices, job.suggestions
    src = Path(job.source)
    if not src.exists():
        raise RuntimeError("The original upload is gone; start a new job.")
    info = media.probe(src)
    thumb_opt = s["thumbnails"][c["thumbnail_index"]]
    _store_metadata(job, {
        "title": c["title"], "description": c["description"], "hashtags": c["hashtags"], "tags": c["tags"],
        "category_id": c["category_id"], "thumbnail_text": c["thumbnail_text"] or thumb_opt["text"],
        "accent_color": thumb_opt["accent_color"],
    })

    music_path = job.dir / "music.wav"
    music_path.unlink(missing_ok=True)  # a rebuild with "No music" must not keep the old track/credit
    if c["music_mood"] != "none":
        job.set(f"Composing original {c['music_mood']} background music", 0.1)
        music.generate(c["music_mood"], info.duration, music_path, seed=int(job.created))

    overlay = None  # (png, x, y)
    if c["title_card"]:
        overlay = graphics.make_title_overlay(job.dir / "title_card.png", job.metadata["title"],
                                              job.metadata["accent_color"], editor.target_size(info))

    job.set("Editing video (format, loudness, fades, music)", 0.2)
    out = editor.finish_video(src, job.dir / "final.mp4", music=music_path if music_path.exists() else None,
                              overlay=overlay, replace_audio=bool(c["replace_audio"]))
    job.files["video"] = out.name

    job.set("Designing thumbnail", 0.92)
    job.files["thumbnail_source"] = thumb_opt["frame"]
    thumb = graphics.make_thumbnail(job.dir / "thumbnail.jpg", job.metadata["thumbnail_text"],
                                    job.metadata["accent_color"], frame=job.dir / thumb_opt["frame"])
    job.files["thumbnail"] = thumb.name
    job.files.pop("thumbnail_preview", None)
    job.copyright = _copyright_report(job, s.get("copyright_review", {}), info)


# ---------------------------------------------------------------- prompt mode

def _process_prompt(job: Job) -> None:
    job.set(f"Writing script and metadata with {_ai_label(job)}", 0.05)
    script = ai.write_video_script(job.prompt, job.options.target_seconds, provider=job.options.ai_provider)
    _store_metadata(job, script)
    scenes = script.get("scenes") or []
    if not scenes:
        raise RuntimeError("Claude returned an empty script. Try a more specific prompt.")
    job.metadata["scenes"] = scenes
    colors = script.get("background_colors") or []
    accent = job.metadata["accent_color"]

    built = []
    for i, scene in enumerate(scenes):
        job.set(f"Rendering scene {i + 1}/{len(scenes)} (slide + voice-over)", 0.15 + 0.5 * i / len(scenes))
        slide = graphics.make_slide(job.dir / "slides" / f"slide_{i:02d}.png", scene["heading"],
                                    scene["on_screen_text"], colors, accent, i, len(scenes))
        voice = tts.synthesize(scene["narration"], job.dir / "voice" / f"voice_{i:02d}.wav")
        if voice:
            seconds = media.audio_duration(voice) + 0.7
        else:  # no TTS voice available: time the slide for reading instead
            seconds = len(scene["narration"].split()) / 2.6
        built.append((slide, voice, max(3.0, seconds)))
    if not any(v for _, v, _ in built):
        job.log.append({"t": time.time(), "msg": "Text-to-speech unavailable; video has music and on-screen text only."})

    job.set("Assembling scenes", 0.68)
    raw = editor.slides_to_video(built, job.dir / "raw.mp4", job.dir / "segments")
    info = media.probe(raw)

    mood = _mood(job, script)
    music_path = None
    if mood != "none":
        job.set(f"Composing original {mood} background music", 0.75)
        music_path = music.generate(mood, info.duration, job.dir / "music.wav", seed=int(job.created))

    job.set("Final mix and encode", 0.8)
    out = editor.finish_video(raw, job.dir / "final.mp4", music=music_path, overlay=None)
    job.files["video"] = out.name

    job.set("Designing thumbnail", 0.94)
    job.files["thumbnail_source"] = "slides/slide_00.png"
    thumb = graphics.make_thumbnail(job.dir / "thumbnail.jpg", job.metadata["thumbnail_text"], accent,
                                    frame=job.dir / job.files["thumbnail_source"])
    job.files["thumbnail"] = thumb.name
    job.copyright = _copyright_report(job, script.get("copyright_review", {}), None)


# ---------------------------------------------------------------- metadata + copyright

def _ai_label(job: Job) -> str:
    info = ai.PROVIDERS.get(job.options.ai_provider, {})
    return f"{info.get('label', job.options.ai_provider)} ({info.get('model', '?')})"


def _mood(job: Job, meta: dict) -> str:
    mood = job.options.music_mood
    if mood == "auto":
        mood = meta.get("music_mood", "calm")
    return mood if mood in ai.MOODS else "calm"


def _clean(text: str) -> str:
    return re.sub(r"[<>]", "", text or "").strip()


def _clean_hashtags(raw: list[str]) -> list[str]:
    hashtags = []
    for h in raw or []:
        h = "#" + re.sub(r"[^\w]", "", str(h).lstrip("#"), flags=re.UNICODE)
        if len(h) > 1 and h.lower() not in {x.lower() for x in hashtags}:
            hashtags.append(h)
    return hashtags


def _store_metadata(job: Job, meta: dict) -> None:
    hashtags = _clean_hashtags(meta.get("hashtags", []))
    job.metadata = {
        "title": _clean(meta.get("title", ""))[:MAX_TITLE] or "Untitled video",
        "description": _clean(meta.get("description", "")),
        "hashtags": hashtags[:MAX_HASHTAGS],
        "tags": _fit_tags([_clean(t).replace(",", " ") for t in meta.get("tags", [])]),
        "category_id": meta.get("category_id") if meta.get("category_id") in ai.CATEGORIES else "22",
        "thumbnail_text": _clean(meta.get("thumbnail_text", "")) or _clean(meta.get("title", "")),
        "accent_color": meta.get("accent_color", "#FFD400"),
    }
    job.save()


def _fit_tags(tags: list[str]) -> list[str]:
    out, total = [], 0
    for t in tags:
        t = t.strip()
        cost = len(t) + (2 if " " in t else 0) + (1 if out else 0)  # YouTube counts quotes + commas
        if t and total + cost <= MAX_TAGS_CHARS:
            out.append(t)
            total += cost
    return out


def full_description(job: Job) -> str:
    m = job.metadata
    parts = [m.get("description", "")]
    if (job.dir / "music.wav").exists():
        parts.append(MUSIC_CREDIT)
    if m.get("hashtags"):
        parts.append(" ".join(m["hashtags"]))
    return "\n\n".join(p for p in parts if p)[:MAX_DESCRIPTION]


def _copyright_report(job: Job, review: dict, info: media.MediaInfo | None) -> dict:
    checks = []
    has_music = (job.dir / "music.wav").exists()
    checks.append({"item": "Background music", "ok": True,
                   "detail": "Generated locally from scratch, no samples or third-party melodies." if has_music else "No music added."})
    checks.append({"item": "Thumbnail & title card", "ok": True,
                   "detail": "Built from your own footage/slides with system fonts."})
    if job.mode == "prompt":
        checks.append({"item": "Visuals & voice-over", "ok": True,
                       "detail": "Original slides and offline text-to-speech from an original script."})
    elif info and info.has_audio and not job.options.replace_audio:
        checks.append({"item": "Original audio track", "ok": False,
                       "detail": "Kept as-is. If any music, radio or TV is audible in the clip, re-run with "
                                 "'Replace original audio' to avoid a Content ID claim."})
    issues = [i for i in review.get("issues", []) if i]
    risk = review.get("risk", "medium")
    checks.append({"item": "AI content review", "ok": risk == "low",
                   "detail": "; ".join(issues) if issues else "No third-party material detected."})
    return {"risk": risk, "issues": issues, "checks": checks}


def _apply_copyright_policy(job: Job) -> None:
    risky = job.copyright.get("risk") in ("medium", "high") or any(not c["ok"] for c in job.copyright.get("checks", []))
    job.status = "needs_review" if risky else "ready"
    job.save()


# ---------------------------------------------------------------- upload

def update_metadata(job: Job, changes: dict) -> None:
    m = job.metadata
    if "title" in changes:
        m["title"] = _clean(changes["title"])[:MAX_TITLE] or m["title"]
    if "description" in changes:
        m["description"] = _clean(changes["description"])
    if "hashtags" in changes:
        _store_metadata(job, {**m, "hashtags": changes["hashtags"], "tags": m["tags"]})
        m = job.metadata
    if "tags" in changes:
        m["tags"] = _fit_tags([_clean(t).replace(",", " ") for t in changes["tags"]])
    if "thumbnail_text" in changes and changes["thumbnail_text"].strip() != m.get("thumbnail_text"):
        m["thumbnail_text"] = _clean(changes["thumbnail_text"])
        source = job.files.get("thumbnail_source")
        graphics.make_thumbnail(job.dir / "thumbnail.jpg", m["thumbnail_text"], m["accent_color"],
                                frame=job.dir / source if source else None)
    job.save()


def upload(job: Job, override_review: bool = False) -> None:
    if job.status == "needs_review" and not override_review:
        raise PermissionError("Copyright review flagged this video. Confirm you own all content before uploading.")
    if job.status not in ("ready", "needs_review", "failed", "uploaded") or "video" not in job.files:
        raise RuntimeError("The video is not ready yet.")
    job.status, job.error = "uploading", None
    job.set("Uploading to YouTube", 0.0)

    def progress(p: float) -> None:
        job.progress = round(p, 3)
        job.save()

    try:
        result = youtube.upload(
            job.dir / job.files["video"], title=job.metadata["title"], description=full_description(job),
            tags=job.metadata["tags"], category_id=job.metadata["category_id"], privacy=job.options.privacy,
            made_for_kids=job.options.made_for_kids, synthetic_media=job.options.synthetic_media,
            thumbnail=job.dir / job.files.get("thumbnail", "thumbnail.jpg"), on_progress=progress,
        )
    except Exception as e:
        job.status, job.error = "failed", str(e)
        job.save()
        raise
    job.youtube = result
    job.status = "uploaded"
    job.set("Uploaded. YouTube is processing the video and running its own copyright checks", 1.0)
    threading.Thread(target=_watch_processing, args=(job,), daemon=True).start()


def upload_async(job: Job, override_review: bool = False) -> None:
    if job.status == "needs_review" and not override_review:
        raise PermissionError("Copyright review flagged this video. Confirm you own all content before uploading.")

    def run():
        try:
            upload(job, override_review)
        except Exception:
            pass  # error is stored on the job
    threading.Thread(target=run, daemon=True).start()


def _watch_processing(job: Job) -> None:
    for _ in range(40):  # ~20 minutes
        time.sleep(30)
        try:
            st = youtube.processing_status(job.youtube["video_id"])
        except Exception:
            continue
        job.youtube["status"] = st
        job.save()
        if st.get("uploadStatus") in ("processed", "rejected", "failed", "deleted"):
            if st.get("uploadStatus") == "rejected":
                job.error = f"YouTube rejected the video: {st.get('rejectionReason')}"
            break
